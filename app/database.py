"""
app/database.py
───────────────
SQLite plumbing: opening the database and creating the table schema.

Why a dedicated module?
- Every part of the app that needs the database should open it the SAME way
  (same safety settings, same schema creation). One module = one truth.

Data-source rule (project policy):
- SQLite is the ONLY source of truth for order information.
- No language model may invent or override an order status.

SQLite comes built into Python (the stdlib "sqlite3" module) — nothing extra
to install.
"""

import sqlite3
from pathlib import Path

from .config import BASE_DIR

# Where the real database file lives: <project root>/data/shop.db
# (this file is generated by "python -m app.seed" and is Git-ignored)
DEFAULT_DB_PATH = str(BASE_DIR / "data" / "shop.db")

# The orders table. order_id is the primary key, so it is unique per row.
# status is restricted to a fixed list of allowed values — this is our first
# line of defense against nonsense/invalid data ("CHECK" constraint).
ORDERS_SCHEMA = """
CREATE TABLE IF NOT EXISTS orders (
    order_id      TEXT PRIMARY KEY,
    customer_name TEXT NOT NULL,
    item          TEXT NOT NULL,
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    status        TEXT NOT NULL CHECK (
        status IN ('pending', 'processing', 'shipped', 'delivered', 'cancelled')
    ),
    created_at    TEXT NOT NULL
);
"""


def get_connection(db_path=None):
    """Open (and if needed, create) the SQLite database and return a connection.

    row_factory = sqlite3.Row lets us access columns BY NAME (row["status"])
    instead of by number, which makes the calling code much more readable.
    """
    path = db_path or DEFAULT_DB_PATH
    # Ensure the folder for the db file exists (e.g. data/ is created on first
    # seed). Git does not track empty directories, so this may be the first run.
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row

    # Enforce foreign key checks (matters more once later phases add relations).
    conn.execute("PRAGMA foreign_keys = ON;")
    return conn


def init_db(db_path=None):
    """Create the tables if they don't exist yet. Safe to call repeatedly
    because of "CREATE TABLE IF NOT EXISTS"."""
    conn = get_connection(db_path)
    try:
        conn.executescript(ORDERS_SCHEMA)
        conn.commit()
    finally:
        conn.close()
